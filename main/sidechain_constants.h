constexpr int SIDECHAIN_STEPS_PER_BEAT = 4;
constexpr int SIDECHAIN_BEATS_PER_PATTERN = 4;
constexpr int SIDECHAIN_PATTERN_LEAD_STEPS = 1;

constexpr int SIDECHAIN_RHYTHM_STEPS = SIDECHAIN_STEPS_PER_BEAT * SIDECHAIN_BEATS_PER_PATTERN;

constexpr int SIDECHAIN_DEPTH_MIN = 0;
constexpr int SIDECHAIN_DEPTH_MAX = 127;
constexpr int SIDECHAIN_DEFAULT_DEPTH = SIDECHAIN_DEPTH_MAX;

constexpr int SIDECHAIN_SHEER_MIN = 0;
constexpr int SIDECHAIN_SHEER_MAX = 127;

constexpr int SIDECHAIN_SHEER_VALUE_COUNT = SIDECHAIN_SHEER_MAX - SIDECHAIN_SHEER_MIN + 1;

constexpr int SIDECHAIN_SHEER_SLOW_BAND_END = SIDECHAIN_SHEER_MIN + SIDECHAIN_SHEER_VALUE_COUNT / 4;
constexpr int SIDECHAIN_SHEER_MEDIUM_BAND_END = SIDECHAIN_SHEER_MIN + SIDECHAIN_SHEER_VALUE_COUNT * 3 / 4;

constexpr float SIDECHAIN_SHEER_SLOW_BAND_WIDTH = static_cast<float>(SIDECHAIN_SHEER_SLOW_BAND_END - SIDECHAIN_SHEER_MIN);
constexpr float SIDECHAIN_SHEER_MEDIUM_BAND_WIDTH = static_cast<float>(SIDECHAIN_SHEER_MEDIUM_BAND_END - SIDECHAIN_SHEER_SLOW_BAND_END);
constexpr float SIDECHAIN_SHEER_FAST_BAND_WIDTH = static_cast<float>(SIDECHAIN_SHEER_MAX - SIDECHAIN_SHEER_MEDIUM_BAND_END);

constexpr float SIDECHAIN_SHEER_SLOW_BAND_ALPHA_FLOOR = 0.01f;
constexpr float SIDECHAIN_SHEER_SLOW_BAND_ALPHA_SPAN = 0.09f;
constexpr float SIDECHAIN_SHEER_MEDIUM_BAND_ALPHA_FLOOR = 0.1f;
constexpr float SIDECHAIN_SHEER_MEDIUM_BAND_ALPHA_SPAN = 0.3f;
constexpr float SIDECHAIN_SHEER_FAST_BAND_ALPHA_FLOOR = 0.4f;
constexpr float SIDECHAIN_SHEER_FAST_BAND_ALPHA_SPAN = 0.59f;

constexpr float sheerSmoothingAlpha(int sheer) {
    if (sheer < SIDECHAIN_SHEER_MIN) sheer = SIDECHAIN_SHEER_MIN;
    if (sheer > SIDECHAIN_SHEER_MAX) sheer = SIDECHAIN_SHEER_MAX;

    if (sheer < SIDECHAIN_SHEER_SLOW_BAND_END) {
        return SIDECHAIN_SHEER_SLOW_BAND_ALPHA_FLOOR
             + (static_cast<float>(sheer - SIDECHAIN_SHEER_MIN) / SIDECHAIN_SHEER_SLOW_BAND_WIDTH)
             * SIDECHAIN_SHEER_SLOW_BAND_ALPHA_SPAN;
    }

    if (sheer < SIDECHAIN_SHEER_MEDIUM_BAND_END) {
        return SIDECHAIN_SHEER_MEDIUM_BAND_ALPHA_FLOOR
             + (static_cast<float>(sheer - SIDECHAIN_SHEER_SLOW_BAND_END) / SIDECHAIN_SHEER_MEDIUM_BAND_WIDTH)
             * SIDECHAIN_SHEER_MEDIUM_BAND_ALPHA_SPAN;
    }

    return SIDECHAIN_SHEER_FAST_BAND_ALPHA_FLOOR
         + (static_cast<float>(sheer - SIDECHAIN_SHEER_MEDIUM_BAND_END) / SIDECHAIN_SHEER_FAST_BAND_WIDTH)
         * SIDECHAIN_SHEER_FAST_BAND_ALPHA_SPAN;
}

